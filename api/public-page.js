import { readFile } from "node:fs/promises";
import { createPublicPageHandler } from "../lib/publicPageServer.js";
import { readSpecialMenuItems } from "./special-menu.js";
import { readPublicDailyMenu } from "./daily-menu.js";

const templatePromises = new Map();
const readTemplate = (language) => {
  if (!["cs", "en", "it"].includes(language)) throw new Error("Unsupported language.");
  if (!templatePromises.has(language)) {
    const promise = readFile(new URL(`../.server/templates/${language}.html`, import.meta.url), "utf8")
      .catch(error => { templatePromises.delete(language); throw error; });
    templatePromises.set(language, promise);
  }
  return templatePromises.get(language);
};

export default createPublicPageHandler({
  // This file is generated by the build; keep loading lazy for local tooling.
  loadRenderer: () => import("../.server/entry-server.js"),
  readTemplate,
  readSpecial: readSpecialMenuItems,
  readDaily: readPublicDailyMenu
});
